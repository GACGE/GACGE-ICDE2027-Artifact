"""Table VI: PR and TC at the two ends of the size sweep (S18D16 -> S25D16) and the density sweep (S20D8 -> S20D256,
15 -> 213 edges per vertex; S20D4 is left out): CPU load-related stalls, GPU scheduler cycles without an issue, and the
GPU speedup. The two cycle fractions describe different events and are compared within each platform only.
  CPU load-related stalls   exe_activity.bound_on_loads / cycles (measure/<pr|tc>-cpu Perf-Stall)
  GPU no-issue cycles       1 - smsp__issue_active / smsp__cycles_active (measure/<pr|tc>-gpu NCU-Issue)
  GPU speedup               CPU / GPU mean runtime (timing legs: GAP, TC on the synthetic graphs GAP-N4; Gunrock)
Writes analysis/graph-properties/outputs/tab_syn_evidence.{tex,md}."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../.."))
sys.path.insert(0, os.path.join(ROOT, "analysis/common"))
from units import leg_runs, mean_ms  # noqa: E402

OUT = f"{ROOT}/analysis/graph-properties/outputs"
TEX = sys.argv[1] if len(sys.argv) > 1 else f"{OUT}/tab_syn_evidence.tex"
os.makedirs(OUT, exist_ok=True)
END = {
    "size": ("SynKronS18D16", "SynKronS25D16"),
    "density": ("SynKronS20D8", "SynKronS20D256"),
}
rows = {}
for prim, u in (("PR", "pr"), ("TC", "tc")):
    stall = leg_runs(f"{u}-cpu", "profile", "Perf-Stall")
    issue = leg_runs(f"{u}-gpu", "profile", "NCU-Issue")
    tcpu = leg_runs(f"{u}-cpu", "timing", "GAP-N4" if u == "tc" else "GAP")
    tgpu = leg_runs(f"{u}-gpu", "timing", "Gunrock")
    for axis, graphs in END.items():
        for g in graphs:
            f, n = stall[g]["profile"]["fields"], issue[g]["profile"]["fields"]
            rows[prim, axis, g] = {
                "CPU load-bound %": 100 * f["perf.exe_activity.bound_on_loads:u"] / f["perf.cycles:u"],
                "GPU no-issue %": 100 * (1 - n["ncu.smsp__issue_active.sum"] / n["ncu.smsp__cycles_active.sum"]),
                "GPU speedup": mean_ms(tcpu[g]["timing"]) / mean_ms(tgpu[g]["timing"])}
METRICS = [
    ("CPU load-related stalls (%)", "CPU load-bound %", 1),
    ("GPU no-issue cycles (%)", "GPU no-issue %", 0),
    ("GPU speedup", "GPU speedup", 2),
]


def pair(prim, axis, col, decimals):
    a, b = (float(rows[prim, axis, graph][col]) for graph in END[axis])
    return f"{a:.{decimals}f}", f"{b:.{decimals}f}"


tex = [
    r"% Generated by analysis/graph-properties/targets/scripts/tab_syn_evidence.py.",
    r"% Density excludes S20D4 pending verification of its profiling scope.",
    r"\begin{table}[!t]",
    r"    \centering",
    r"    \caption{CPU load-related stalls, GPU no-issue cycles, and GPU speedup.}",
    r"    \label{tab:syn-evidence}",
    r"    \scriptsize",
    r"    \setlength{\tabcolsep}{2pt}",
    r"    \renewcommand{\arraystretch}{1.0}",
    r"    \begin{tabular*}{0.95\columnwidth}{@{\extracolsep{\fill}}llccc@{}}",
    r"        \toprule",
    r"        \textbf{Primitive} & \textbf{Property} & \shortstack{\textbf{CPU load-related}\\\textbf{stalls (\%)}} & \shortstack{\textbf{GPU no-issue}\\\textbf{cycles (\%)}} & \shortstack{\textbf{GPU}\\\textbf{speedup} ($\times$)} \\",
    r"        \midrule",
]
md = [
    "# PR and TC stalls and GPU speedup across graph-property sweeps\n",
    "Source: Perf-Stall, NCU-Issue and the timing legs.\n",
    "Size: 0.17M -> 17M vertices. Density: 15 -> 213 edges per vertex.",
    "Density omits S20D4 pending verification of its profiling scope.\n",
]
for i, prim in enumerate(("PR", "TC")):
    if i:
        tex.append(r"        \midrule")
    md += [
        f"## ({chr(97 + i)}) {prim}\n",
        "| Sweep | " + " | ".join(label for label, *_ in METRICS) + " |",
        "|---|" + "---:|" * len(METRICS),
    ]
    for axis in ("size", "density"):
        values = [pair(prim, axis, col, decimals) for _, col, decimals in METRICS]
        group = (r"\multirow{2}{*}{\textbf{(" + chr(97 + i) + ") " + prim + "}}"
                 if axis == "size" else "")
        tex.append("        " + group + " & " + axis.title() + " & " +
                   " & ".join(f"${a}\\!\\to\\!{b}$" for a, b in values) + r" \\")
        md.append("| " + axis.title() + " | " + " | ".join(f"{a} → {b}" for a, b in values) + " |")
    md.append("")
tex += [
    r"        \bottomrule",
    r"    \end{tabular*}",
    r"    \par\smallskip",
    r"    \begin{minipage}{0.95\columnwidth}",
    r"    \raggedright $a \to b$: Size, 0.17M $\to$ 17M vertices; Density, 15 $\to$ 213 edges/vertex. \textit{CPU load-related stalls}: fraction of time waiting for data. \textit{GPU no-issue cycles}: fraction of active GPU scheduler cycles without instruction issue. \textit{GPU speedup}: CPU runtime/GPU runtime at each graph setting.\par",
    r"    \end{minipage}",
    r"\end{table}",
]
md.append("CPU load-related stalls: fraction of time waiting for data. "
          "GPU no-issue cycles: fraction of active GPU scheduler cycles without instruction issue. "
          "GPU speedup: CPU runtime / GPU runtime. "
          "The cycle fractions describe different events; compare trends within each platform.")
with open(TEX, "w") as target:
    target.write("\n".join(tex) + "\n")
with open(f"{OUT}/tab_syn_evidence.md", "w") as target:
    target.write("\n".join(md) + "\n")
print("\n".join(md))
