"""Table of the evaluated graphs (Sec. III): |V|, |E| (undirected) and density |E| / |V|, rows by |V|, from the sizes GAP
reports when it loads each graph (analysis/common/graphs.py). Writes analysis/datasets/outputs/tab_graph_metrics_ci.tex."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../../../common"))
from graphs import graph_size  # noqa: E402

OUT = os.path.join(HERE, "../../outputs/tab_graph_metrics_ci.tex")
GRAPHS = ["Youtube", "Kron21", "Orkut", "HiggsNets", "Amazon", "UK2002", "Arabic", "Sinaweibo"]
NAMES = {"UK2002": "UK-2002"}

rows = sorted((graph_size(g) + (g,) for g in GRAPHS))
tex = [r"% generated by analysis/datasets/targets/scripts/tab_graph_metrics.py",
       r"\begin{table}[H]",
       r" \centering",
       r" \caption{Evaluated graphs: vertices, undirected edges, and density (average edges per vertex, $|E|/|V|$).}",
       r" \label{tab:graph-metrics}",
       r" \footnotesize",
       r" \setlength{\tabcolsep}{4pt}",
       r" \begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrr@{}}",
       r" \toprule",
       r" \textbf{Graph} & \boldmath$|V|$ & \boldmath$|E|$ & \textbf{Density} \\",
       r" \midrule"]
tex += [f" {NAMES.get(g, g)} & {v:,} & {e:,} & {e / v:.2f} \\\\" for v, e, g in rows]
tex += [r" \bottomrule", r" \end{tabular*}", r"\end{table}"]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(tex) + "\n")
print("->", os.path.abspath(OUT))
