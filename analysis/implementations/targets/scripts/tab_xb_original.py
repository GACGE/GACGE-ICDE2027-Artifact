"""XB-GAP against the original X-Blossom CPU implementation (src/xb-original, Fan et al., PVLDB 2025) on the paper's
eight graphs, from measure/xb-cpu's XB-Original leg (one session, 1 warm-up + 10 runs each):

  original   the original's own "computation time" (its three search phases), the mean of 10 runs, at its
             faster thread count (96 or 48 std::threads) per graph; the bookkeeping between the phases that it
             leaves out of that time is in the detail table (total)
  XB-GAP     the gap96 run (every hardware thread), as the XB-GAP leg
  speedup    original / XB-GAP; the mean row is the arithmetic mean over the graphs (the geometric mean beside it)

Writes analysis/implementations/outputs/tab_xb_original{.csv,.md,.tex}."""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../common"))
from units import *  # noqa: E402,F403

OUT = os.path.join(ANALYSIS, "implementations", "outputs")
ALL = ["Amazon", "HiggsNets", "Youtube", "Kron21", "Orkut", "UK2002", "Arabic", "Sinaweibo"]
NAMES = {"UK2002": "UK-2002"}
gm = lambda v: math.exp(sum(map(math.log, v)) / len(v))


def mean_s(run, key="runtime_s"):
    v = run["samples"][key]
    return sum(v) / len(v)


runs = leg_runs("xb-cpu", "timing", "XB-Original")
rows = []
for g in ALL:
    r = runs.get(g, {})
    if not all(t in r for t in ("orig96", "orig48", "gap96")):
        sys.exit(f"tab_xb_original: {g} lacks an ok orig96/orig48/gap96 run")
    t96, t48 = mean_s(r["orig96"]), mean_s(r["orig48"])
    best = "orig96" if t96 <= t48 else "orig48"
    orig, total, ours = min(t96, t48), mean_s(r[best], "total_s"), mean_s(r["gap96"])
    rows.append(dict(graph=g, orig_threads=best[4:], orig_s=orig, orig_total_s=total, orig96_s=t96, orig48_s=t48,
                     xbgap_s=ours, speedup=orig / ours, speedup_total=total / ours))

sp = [r["speedup"] for r in rows]
mean, geo = sum(sp) / len(sp), gm(sp)
os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "tab_xb_original.csv"), "w") as f:
    keys = list(rows[0])
    f.write(",".join(keys) + "\n")
    for r in rows:
        f.write(",".join(f"{r[k]:.6f}" if isinstance(r[k], float) else str(r[k]) for k in keys) + "\n")

md = [f"# XB-GAP vs the original X-Blossom CPU implementation ({CPU_MACHINE})", "",
      "| Graph | Original (s) | threads | Original total (s) | XB-GAP (s) | Speedup | Speedup (total) |",
      "|---|---:|---:|---:|---:|---:|---:|"]
for r in rows:
    md.append(f"| {NAMES.get(r['graph'], r['graph'])} | {r['orig_s']:.3f} | {r['orig_threads']} | {r['orig_total_s']:.3f} "
              f"| {r['xbgap_s']:.3f} | {r['speedup']:.2f}x | {r['speedup_total']:.2f}x |")
spt = [r["speedup_total"] for r in rows]
md += [f"| **Mean** | | | | | **{mean:.2f}x** | **{sum(spt) / len(spt):.2f}x** |",
       f"| GM | | | | | {geo:.2f}x | {gm(spt):.2f}x |"]
open(os.path.join(OUT, "tab_xb_original.md"), "w").write("\n".join(md) + "\n")

tex = [f"% generated by analysis/implementations/targets/scripts/tab_xb_original.py ({CPU_MACHINE})",
       "% Original: its own computation time at its faster thread count (96 or 48); XB-GAP: 96 threads; 1 warm-up + 10 runs.",
       "\\begin{table}[H]", " \\centering",
       " \\caption{Runtime of the Original and Our OpenMP CPU Implementations of XB.}",
       " \\label{tab:xb-original}", " \\footnotesize", " \\setlength{\\tabcolsep}{4pt}",
       " \\begin{tabular*}{\\columnwidth}{@{\\extracolsep{\\fill}}lrrr@{}}", " \\toprule",
       " \\textbf{Graph} & \\textbf{Original (s)} & \\textbf{Ours (s)} & \\textbf{Speedup} \\\\", " \\midrule"]
for r in rows:
    tex.append(f" {NAMES.get(r['graph'], r['graph'])} & {r['orig_s']:.3f} & {r['xbgap_s']:.3f} & {r['speedup']:.2f}$\\times$ \\\\")
tex += [" \\midrule", f" \\textbf{{Mean}} & \\textbf{{--}} & \\textbf{{--}} & \\textbf{{{mean:.2f}$\\times$}} \\\\",
        " \\bottomrule", " \\end{tabular*}", "\\end{table}"]
open(os.path.join(OUT, "tab_xb_original.tex"), "w").write("\n".join(tex) + "\n")
print("\n".join(md))
