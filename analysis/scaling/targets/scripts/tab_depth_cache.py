"""The depth step of Fig. 9 in the memory hierarchy, as one single-column table (the data of plot_depth_cache.py):
  CPU   48 -> 96 threads on the 48 cores: L1 hit %, L2 hit % of the loads missing L1, LLC hit % of the loads missing
        L2 (mean over the eight graphs; outputs/cpu_smt.csv, cpu_cores_table.py's formulas), L1 misses in flight
        per core (GM), and the 96/48 speedup (GM; outputs/cpu_breadth_depth.csv)
  GPU   1 -> 11 resident blocks an SM on all 188 SMs, the paper's default kernels with the grid capped at k blocks an
        SM (GACGE_GPU_GRID_K, no shared-memory pad; 2026-10-24): L1 hit % of global-load sectors, L2 hit % (mean;
        outputs/depth_diag_gc_<graph>.csv), warps waiting on memory per SM (GM), and the 11/1 speedup (GM;
        outputs/breadth_depth_gc.csv)
Writes analysis/scaling/outputs/tab_depth_cache.{md,tex}."""
import math
import os
import sys
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../.."))
OUT = f"{ROOT}/analysis/scaling/outputs"; TEX = f"{OUT}/tab_depth_cache.tex"
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../common"))
from units import leg_runs, mean_ms  # noqa: E402
U = ["bfs", "sssp", "xb", "pr", "tc"]; NAME = {"bfs": "BFS", "sssp": "SSSP", "xb": "XB", "pr": "PR", "tc": "TC"}
GR = ["Kron21", "Orkut", "UK2002", "Arabic", "Sinaweibo", "Amazon", "HiggsNets", "Youtube"]  # all eight graphs
if os.environ.get("GRAPHS") == "large":  # the five large graphs only (the paper until 2026-10-24)
    GR = GR[:5]
gm = lambda xs: math.exp(sum(math.log(x) for x in xs) / len(xs))
mean = lambda xs: sum(xs) / len(xs)

v = defaultdict(dict)  # (unit, graph, threads) -> {perf event: count}, the l1 / mem / ipc runs of Perf-SMT
for u in NAME:
    for gr, runs in leg_runs(f"{u}-cpu", "profile", "Perf-SMT").items():
        for tag, r in runs.items():
            t = int(tag.split("-")[1])
            for k, x in r["fields"].items():
                if k.startswith("perf."):
                    v[u, gr, t][k[5:].split(":")[0]] = x
cms = {(u, gr, int(tag[1:])): mean_ms(r) for u in NAME for gr, runs in leg_runs(f"{u}-cpu", "timing", "Threads").items()
       for tag, r in runs.items()}


def cpu_metrics(d, t):
    pause = d.get("cpu_clk_unhalted.pause_inst", 0)
    loads = d["mem_inst_retired.all_loads"] - pause
    l1 = (d["mem_load_retired.l1_hit"] - pause + d.get("mem_load_retired.fb_hit", 0)) / loads
    f2 = d["mem_load_retired.l2_miss"] / loads; f3 = d["mem_load_retired.l3_miss"] / loads
    f1 = max(1 - l1, f2)
    return 100 * l1, 100 * (f1 - f2) / f1, 100 * (f2 - f3) / f2, d["l1d_pend_miss.pending"] / (d["cycles"] - d.get("cpu_clk_unhalted.pause", 0)) * (2 if t == 96 else 1)


cpu = {}
for u in U:
    for t in (48, 96):
        rows = [cpu_metrics(v[u, g, t], t) for g in GR]
        cpu[u, t] = [mean([r[i] for r in rows]) for i in range(3)] + [gm([r[3] for r in rows])]
    cpu[u, "sp"] = gm([cms[u, g, 48] / cms[u, g, 96] for g in GR])

g = defaultdict(dict)  # (unit, graph, blocks an SM) -> {ncu metric: sum}, groups a and b of NCU-Depth
for u in NAME:
    for gr, runs in leg_runs(f"{u}-gpu", "profile", "NCU-Depth").items():
        for tag, r in runs.items():
            k = int(tag.split("-")[0][1:])
            g[u, gr, k].update({m[4:]: x for m, x in r["fields"].items() if m.startswith("ncu.") and m != "ncu.kernels"})
gms = {(u, gr, int(tag.split("k")[1])): mean_ms(r) for u in NAME
       for gr, runs in leg_runs(f"{u}-gpu", "timing", "Breadth-Depth").items() for tag, r in runs.items() if tag.startswith("s188")}
gpu = {}
for u in U:
    for k in (1, 11):
        l1, l2, wait = [], [], []
        for gr in GR:
            d = g[u, gr, k]
            h, m = d["l1tex__t_sectors_pipe_lsu_mem_global_op_ld_lookup_hit.sum"], d["l1tex__t_sectors_pipe_lsu_mem_global_op_ld_lookup_miss.sum"]
            lh, lm = d["lts__t_sectors_lookup_hit.sum"], d["lts__t_sectors_lookup_miss.sum"]
            l1.append(100 * h / (h + m)); l2.append(100 * lh / (lh + lm))
            wait.append(4 * d["smsp__warps_issue_stalled_long_scoreboard.sum"] / d["smsp__cycles_active.sum"])
        gpu[u, k] = (mean(l1), mean(l2), gm(wait))
        gpu[u, k, "sp"] = gm([gms[u, gr, 1] / gms[u, gr, k] for gr in GR])

arrow = lambda a, b, d=0: f"{a:.{d}f} $\\to$ {b:.{d}f}"
md = ["# The depth step in the memory hierarchy (eight graphs: hit rates mean, in-flight GM, speedup GM)\n",
      "| | L1 hit % | L2 hit % | LLC hit % | In flight | Speedup |", "|---|---|---|---|---|---|"]
tex = [r"% Generated by analysis/scaling/targets/scripts/tab_depth_cache.py (Perf-SMT, NCU-Depth, Threads, Breadth-Depth legs).",
       r"\begin{table}[t]", r"    \centering",
       r"    \caption{Cache behavior and concurrency during depth scaling.}",
       r"    \label{tab:depth-cache}",
       r"    \footnotesize", r"    \setlength{\tabcolsep}{3pt}",
       r"    \renewcommand{\arraystretch}{1.12}",
       r"    \makebox[\columnwidth][l]{\textbf{(a) CPU}\quad 48 $\to$ 96 threads}", r"    \par\smallskip",
       r"    \begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lccccc@{}}", r"        \toprule",
       r"        \multirow{2}{*}{\textbf{Primitive}} & \multicolumn{3}{c}{\textbf{Cache hit rate (\%)}} & \multirow{2}{*}{\shortstack{\textbf{L1 misses}\\\textbf{per core}}} & \multirow{2}{*}{\shortstack{\textbf{Speedup}\\($\times$)}} \\",
       r"        \cmidrule(lr){2-4}",
       r"        & L1 & L2 & LLC & & \\",
       r"        \midrule"]
for u in U:
    a, b = cpu[u, 48], cpu[u, 96]
    md.append(f"| CPU {NAME[u]} | {arrow(a[0], b[0])} | {arrow(a[1], b[1])} | {arrow(a[2], b[2])} | {arrow(a[3], b[3], 1)} | {cpu[u, 'sp']:.2f} |")
    tex.append(f"        {NAME[u]} & {arrow(a[0], b[0])} & {arrow(a[1], b[1])} & {arrow(a[2], b[2])} & {arrow(a[3], b[3], 1)} & {cpu[u, 'sp']:.2f} \\\\")
tex += [r"        \bottomrule", r"    \end{tabular*}", r"    \par\medskip",
        r"    \makebox[\columnwidth][l]{\textbf{(b) GPU}\quad 1 $\to$ 11 resident blocks per SM}", r"    \par\smallskip",
        r"    \begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lcccc@{}}", r"        \toprule",
        r"        \multirow{2}{*}{\textbf{Primitive}} & \multicolumn{2}{c}{\textbf{Cache hit rate (\%)}} & \multirow{2}{*}{\shortstack{\textbf{Waiting warps}\\\textbf{per SM}}} & \multirow{2}{*}{\shortstack{\textbf{Speedup}\\($\times$)}} \\",
        r"        \cmidrule(lr){2-3}", r"        & L1 & L2 & & \\", r"        \midrule"]
for u in U:
    a, b = gpu[u, 1], gpu[u, 11]
    sp = gpu[u, 11, "sp"]; note = ""
    md.append(f"| GPU {NAME[u]} | {arrow(a[0], b[0])} | {arrow(a[1], b[1])} | | {arrow(a[2], b[2], 1)} | {sp:.2f}{note} |")
    tex.append(f"        {NAME[u]} & {arrow(a[0], b[0])} & {arrow(a[1], b[1])} & {arrow(a[2], b[2], 1)} & {sp:.2f}{note} \\\\")
tex += [r"        \bottomrule", r"    \end{tabular*}", r"\end{table}"]
os.makedirs(OUT, exist_ok=True)
open(f"{OUT}/tab_depth_cache.md", "w").write("\n".join(md) + "\n")
open(TEX, "w").write("\n".join(tex) + "\n")
print("\n".join(md))
